// Generates src/SolTechnology.Time/ZoneLinks.g.cs from the IANA tz database.
// Run from the repository root:  dotnet run tools/GenerateZoneLinks.cs [path-to-tzdata.tar.gz]
// Without an argument it downloads https://data.iana.org/time-zones/tzdata-latest.tar.gz.
using System.Formats.Tar;
using System.IO.Compression;
using System.Text;

// Links in tzdb are of two kinds: renamed/legacy names (Europe/Kiev -> Europe/Kyiv, Poland -> Europe/Warsaw) and locations
// merged because they agree since 1970 (Europe/Oslo -> Europe/Berlin). Only the first kind is an alias. Every location in
// zone.tab (one per country) stays a canonical name of its own, even when the tzdb data makes it a link.
string[] sources = ["africa", "antarctica", "asia", "australasia", "europe", "northamerica", "southamerica", "etcetera", "backward"];

Stream archive = args.Length > 0
    ? File.OpenRead(args[0])
    : await new HttpClient().GetStreamAsync("https://data.iana.org/time-zones/tzdata-latest.tar.gz");

var files = new Dictionary<string, string>();
await using (var gzip = new GZipStream(archive, CompressionMode.Decompress))
await using (var tar = new TarReader(gzip))
{
    while (await tar.GetNextEntryAsync() is { } entry)
    {
        if (entry.DataStream is null) continue;
        using var reader = new StreamReader(entry.DataStream);
        files[entry.Name] = await reader.ReadToEndAsync();
    }
}

var version = files["version"].Trim();
var zones = new SortedSet<string>(StringComparer.Ordinal);
var links = new Dictionary<string, string>(StringComparer.Ordinal);
foreach (var source in sources)
{
    foreach (var raw in files[source].Split('\n'))
    {
        var line = raw.Split('#')[0];
        var parts = line.Split((char[])[' ', '\t'], StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length >= 2 && parts[0] == "Zone") zones.Add(parts[1]);
        else if (parts.Length >= 3 && parts[0] == "Link") links[parts[2]] = parts[1];
    }
}

foreach (var raw in files["zone.tab"].Split('\n'))
{
    if (raw.StartsWith('#')) continue;
    var parts = raw.Split('\t');
    if (parts.Length >= 3)
    {
        zones.Add(parts[2]);
        links.Remove(parts[2]);
    }
}

string Target(string name)
{
    var seen = new HashSet<string>();
    while (links.TryGetValue(name, out var next) && seen.Add(name)) name = next;
    return name;
}

var output = new StringBuilder();
output.AppendLine("// <auto-generated>");
output.AppendLine($"// Generated by tools/GenerateZoneLinks.cs from tzdata {version}. Do not edit.");
output.AppendLine("// </auto-generated>");
output.AppendLine("namespace SolTechnology.Time;");
output.AppendLine();
output.AppendLine("internal static class ZoneLinks");
output.AppendLine("{");
output.AppendLine($"    public const string TzdbVersion = \"{version}\";");
output.AppendLine();
output.AppendLine("    /// <summary>Canonical zone names: tzdb <c>Zone</c> lines and every location in <c>zone.tab</c>.</summary>");
output.AppendLine("    public static readonly HashSet<string> Zones = new(StringComparer.OrdinalIgnoreCase)");
output.AppendLine("    {");
foreach (var zone in zones) output.AppendLine($"        \"{zone}\",");
output.AppendLine("    };");
output.AppendLine();
output.AppendLine("    /// <summary>Renamed or legacy name to its canonical name (tzdb <c>Link</c> lines minus <c>zone.tab</c> locations, chains resolved).</summary>");
output.AppendLine("    public static readonly Dictionary<string, string> Links = new(StringComparer.OrdinalIgnoreCase)");
output.AppendLine("    {");
foreach (var (name, _) in links.OrderBy(l => l.Key, StringComparer.Ordinal)) output.AppendLine($"        [\"{name}\"] = \"{Target(name)}\",");
output.AppendLine("    };");
output.AppendLine("}");

var path = Path.Combine("src", "SolTechnology.Time", "ZoneLinks.g.cs");
await File.WriteAllTextAsync(path, output.ToString());
Console.WriteLine($"tzdata {version}: {zones.Count} zones, {links.Count} links -> {path}");
